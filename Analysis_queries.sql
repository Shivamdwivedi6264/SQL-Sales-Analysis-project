use shiv_shop;
-- Basic sql question
-- 1 How many total customers are there?
SELECT COUNT(*) AS total_customers
FROM customers;

-- 2 How many total products are there?
SELECT COUNT(*) AS total_products
FROM products;

-- 3 Display the top 5 most expensive products.
SELECT *
FROM products
ORDER BY price DESC
LIMIT 5;

-- 4 Display all unique cities where customers live.
SELECT DISTINCT city
FROM customers;

-- 5 Display orders sorted by the latest order date.
SELECT *
FROM orders
ORDER BY order_date DESC;

-- intermediate sql question
-- 6 How many orders has each customer placed?
SELECT
    c.customer_id,
    c.name,
    COUNT(o.order_id) AS total_orders
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.name;

-- 7 Calculate the total quantity sold for each product.
SELECT
    p.product_id,
    p.product_name,
    SUM(oi.quantity) AS total_quantity_sold
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.product_id, p.product_name;

-- 8 Calculate the total sales amount generated by each product.
SELECT
    p.product_id,
    p.product_name,
    SUM(oi.quantity * p.price) AS total_sales
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.product_id, p.product_name
ORDER BY total_sales DESC;

-- 9 Calculate the total sales for each product category.
SELECT
    p.category,
    SUM(oi.quantity * p.price) AS total_sales
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.category
ORDER BY total_sales DESC;

-- 10 Find the top 10 customers by total spending.
SELECT
    c.customer_id,
    c.name,
    SUM(oi.quantity * p.price )AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
ON oi.product_id = p.product_id
GROUP BY c.customer_id, c.name
ORDER BY total_spending DESC
LIMIT 10;

-- 11 Count the number of payments made using each payment method.
SELECT
    payment_mode,
    COUNT(*) AS total_payments
FROM payments
GROUP BY payment_mode;


-- 12 Find customers who have never placed an order.
SELECT
    c.customer_id,
    c.name
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
WHERE o.order_id IS NULL;

-- 13 Find products that have never been ordered.
SELECT
    p.product_id,
    p.product_name
FROM products p
LEFT JOIN order_items oi
    ON p.product_id = oi.product_id
WHERE oi.product_id IS NULL;

-- 14 Calculate month-wise total sales.
SELECT
    DATE_FORMAT(o.order_date, '%Y-%m') AS sales_month,
    SUM(oi.quantity * p.price) AS total_sales
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id
GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
ORDER BY sales_month;

-- 15 Calculate the number of orders for each month.
SELECT
    DATE_FORMAT(order_date, '%Y-%m') AS order_month,
    COUNT(*) AS total_orders
FROM orders
GROUP BY DATE_FORMAT(order_date, '%Y-%m')
ORDER BY order_month;

-- .16 Calculate the Average Order Value (AOV).
SELECT
    SUM(oi.quantity * p.price) / COUNT(DISTINCT o.order_id)
        AS average_order_value
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id;
    
    -- 17 Find the top 5 products generating the highest revenue.
    SELECT
    p.product_id,
    p.product_name,
    SUM(oi.quantity * p.price) AS total_revenue
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.product_id, p.product_name
ORDER BY total_revenue DESC
LIMIT 5;

-- 18 Display each customer's total spending and order count.
SELECT
    c.customer_id,
    c.name,
    COALESCE(SUM(oi.quantity * p.price), 0) AS total_spending,
    COUNT(DISTINCT o.order_id) AS order_count
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
LEFT JOIN order_items oi
    ON o.order_id = oi.order_id
LEFT JOIN products p
    ON oi.product_id = p.product_id
GROUP BY c.customer_id, c.name
ORDER BY total_spending DESC;

-- 19 Find products priced above the average product price.
SELECT
    product_id,
    product_name,
    price
FROM products
WHERE price > (
    SELECT AVG(price)
    FROM products
);

-- 20 Find the highest-priced product in each category.
SELECT
    p.product_id,
    p.product_name,
    p.category,
    p.price
FROM products p
WHERE p.price = (
    SELECT MAX(p2.price)
    FROM products p2
    WHERE p2.category = p.category
)
ORDER BY p.category;

-- 21 Calculate the sales difference between each month and the previous month.
WITH monthly_sales AS (
    SELECT
        DATE_FORMAT(o.order_date, '%Y-%m') AS sales_month,
        SUM(oi.quantity * p.price) AS total_sales
    FROM orders o
    JOIN order_items oi
        ON o.order_id = oi.order_id
    JOIN products p
        ON oi.product_id = p.product_id
    GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
)
SELECT
    sales_month,
    total_sales,
    LAG(total_sales) OVER (
        ORDER BY sales_month
    ) AS previous_month_sales,
    total_sales - LAG(total_sales) OVER (
        ORDER BY sales_month
    ) AS sales_difference
FROM monthly_sales
ORDER BY sales_month;

-- 22 Rank products according to their total sales.
WITH product_sales AS (
    SELECT
        p.product_id,
        p.product_name,
        SUM(oi.quantity * p.price) AS total_sales
    FROM products p
    JOIN order_items oi
        ON p.product_id = oi.product_id
    GROUP BY p.product_id, p.product_name
)
SELECT
    product_id,
    product_name,
    total_sales,
    RANK() OVER (
        ORDER BY total_sales DESC
    ) AS sales_rank
FROM product_sales
ORDER BY sales_rank;

-- 23 Which month performed best in terms of revenue?
SELECT
    DATE_FORMAT(o.order_date, '%Y-%m') AS sales_month,
    SUM(oi.quantity * p.price) AS total_revenue
FROM orders o
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id
GROUP BY DATE_FORMAT(o.order_date, '%Y-%m')
ORDER BY total_revenue DESC
LIMIT 1;

-- 24 Which customers spent the most?
SELECT
    c.customer_id,
    c.name,
    SUM(oi.quantity * p.price) AS total_spending
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_items oi
    ON o.order_id = oi.order_id
JOIN products p
    ON oi.product_id = p.product_id
GROUP BY c.customer_id, c.name
ORDER BY total_spending DESC
LIMIT 10;

-- 25 Which products are in the highest demand?
SELECT
    p.product_id,
    p.product_name,
    SUM(oi.quantity) AS total_quantity_sold
FROM products p
JOIN order_items oi
    ON p.product_id = oi.product_id
GROUP BY p.product_id, p.product_name
ORDER BY total_quantity_sold DESC
LIMIT 10;

    -- 26 Find the first and latest order dates for each customer.
    SELECT
    c.customer_id,
    c.name,
    MIN(o.order_date) AS first_order_date,
    MAX(o.order_date) AS latest_order_date
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
GROUP BY c.customer_id, c.name
ORDER BY c.customer_id;

 











